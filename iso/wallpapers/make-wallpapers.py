#!/usr/bin/env python3
"""Draw the Kiln wallpapers.

The walls are drawn here instead of downloaded: the medium has to work with no
network at all, and a PNG generated by this script carries no licence to argue
about.  Run it from the repository root:

    python3 iso/wallpapers/make-wallpapers.py

It writes installer/assets/wallpapers/*.png, which the installer copies into
/usr/share/backgrounds/kiln in the new system (installer/xfce.py).  Only the
standard library is used, so it runs anywhere Python 3 does.
"""

from __future__ import annotations

import math
import os
import struct
import sys
import zlib

WIDTH, HEIGHT = 2560, 1440
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "installer", "assets", "wallpapers")
_exp, _sqrt = math.exp, math.sqrt


def write_png(path: str, rows) -> int:
    """Write 8-bit RGB rows as a PNG, and return the size on disk."""
    raw = b"".join(b"\x00" + row for row in rows)

    def chunk(kind: bytes, data: bytes) -> bytes:
        body = kind + data
        return (
            struct.pack(">I", len(data))
            + body
            + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)
        )

    header = struct.pack(">IIBBBBB", WIDTH, HEIGHT, 8, 2, 0, 0, 0)
    image = (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", header)
        + chunk(b"IDAT", zlib.compress(raw, 9))
        + chunk(b"IEND", b"")
    )
    with open(path, "wb") as handle:
        handle.write(image)
    return len(image)


def render(pixel) -> list:
    """Turn a ``pixel(u, v) -> (r, g, b)`` function into rows of bytes."""
    rows = []
    for y in range(HEIGHT):
        v = y / (HEIGHT - 1)
        row = bytearray(WIDTH * 3)
        index = 0
        for x in range(WIDTH):
            u = x / (WIDTH - 1)
            r, g, b = pixel(u, v)
            row[index] = 0 if r < 0 else 255 if r > 255 else int(r)
            row[index + 1] = 0 if g < 0 else 255 if g > 255 else int(g)
            row[index + 2] = 0 if b < 0 else 255 if b > 255 else int(b)
            index += 3
        rows.append(bytes(row))
    return rows


def aurora(u: float, v: float):
    """Deep blue-black with a cyan glow above and an ember glow below."""
    r, g, b = 7 + 26 * v, 10 + 34 * v, 16 + 46 * v
    d = ((u - 0.80) ** 2) * 1.1 + ((v - 0.16) ** 2) * 1.9
    glow = 240 * _exp(-d * 7.0)
    r += glow * 0.18
    g += glow * 0.62
    b += glow * 0.78
    d = ((u - 0.14) ** 2) * 1.5 + ((v - 0.90) ** 2) * 2.1
    glow = 200 * _exp(-d * 9.0)
    r += glow * 0.95
    g += glow * 0.55
    b += glow * 0.22
    band = _exp(-((v - 0.63) ** 2) * 2600.0) * (0.35 + 0.65 * u)
    r += 70 * band
    g += 190 * band
    b += 210 * band
    if (int(u * WIDTH) & 127) == 0:
        k = 0.30 * (1.0 - 0.6 * v)
        r += 90 * k
        g += 160 * k
        b += 200 * k
    return r, g, b


def grid(u: float, v: float):
    """A perspective floor running to a glowing horizon."""
    r, g, b = 6 + 18 * v, 9 + 26 * v, 14 + 34 * v
    horizon = 0.56
    if v > horizon:
        t = (v - horizon) / (1.0 - horizon)
        glow = _exp(-(t * t) * 26.0)
        r += 30 * glow
        g += 120 * glow
        b += 150 * glow
        depth = 1.0 / (1.0 - min(t, 0.985) * 0.95)
        column = (u - 0.5) * depth * 24.0
        if abs(column - round(column)) < 0.02 + 0.0015 * depth:
            k = 0.45 * (1.0 - t * 0.55)
            r += 55 * k
            g += 150 * k
            b += 190 * k
        line = depth * 3.0
        if abs(line - round(line)) < 0.03 + 0.004 * depth:
            k = 0.35 * (1.0 - t * 0.40)
            r += 50 * k
            g += 140 * k
            b += 180 * k
    else:
        haze = _exp(-((v - horizon) ** 2) * 22.0) * _exp(-((u - 0.5) ** 2) * 6.0)
        r += 20 * haze
        g += 80 * haze
        b += 105 * haze
    return r, g, b


def ember(u: float, v: float):
    """A warm core ringed in cyan, on near-black with a fine dot grid."""
    r, g, b = 10 + 26 * v, 8 + 16 * v, 10 + 18 * v
    dx = (u - 0.62) * 1.55
    dy = v - 0.46
    dist = _sqrt(dx * dx + dy * dy)
    ring = _exp(-((dist - 0.30) ** 2) * 520.0)
    r += 250 * ring
    g += 120 * ring
    b += 32 * ring
    ring2 = _exp(-((dist - 0.38) ** 2) * 900.0)
    r += 60 * ring2
    g += 190 * ring2
    b += 220 * ring2
    core = _exp(-(dist * dist) * 42.0)
    r += 70 * core
    g += 40 * core
    b += 30 * core
    if (int(u * WIDTH) & 63) < 2 and (int(v * HEIGHT) & 63) < 2:
        r += 30
        g += 40
        b += 46
    return r, g, b


WALLPAPERS = (
    ("kiln-001-aurora.png", aurora),
    ("kiln-002-grid.png", grid),
    ("kiln-003-ember.png", ember),
)


def main() -> int:
    os.makedirs(OUT, exist_ok=True)
    for name, pixel in WALLPAPERS:
        path = os.path.join(OUT, name)
        size = write_png(path, render(pixel))
        print("%s  %dx%d  %.1f MiB" % (name, WIDTH, HEIGHT, size / 1048576.0))
    return 0


if __name__ == "__main__":
    sys.exit(main())
